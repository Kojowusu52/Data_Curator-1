function summarizeEventsForCatalog(
  id: string,
  presetId: string,
  name: string,
  domain: string,
  description: string,
  events: RawEvent[],
  isActive: boolean,
  isCustom: boolean
): DatasetCatalogEntry {
  const entities = new Set<string>();
  const channels = new Set<string>();
  const actionMap = new Map<number, string>();
  let minDay = events.length > 0 ? Infinity : 0;
  let maxDay = events.length > 0 ? -Infinity : 0;
  let totalSpend = 0;
  let totalReward = 0;
  let totalEngagement = 0;
  let totalPropensity = 0;

  for (const ev of events) {
    entities.add(ev.entityId);
    channels.add(ev.channel);
    if (!actionMap.has(ev.actionId)) {
      actionMap.set(ev.actionId, ev.actionLabel);
    }
    if (ev.timestampDay < minDay) minDay = ev.timestampDay;
    if (ev.timestampDay > maxDay) maxDay = ev.timestampDay;
    totalSpend += ev.spendAmount;
    totalReward += ev.reward;
    totalEngagement += ev.engagementScore;
    totalPropensity += ev.propensity;
  }

  const n = Math.max(1, events.length);
  const health = computeDataHealthScorecard(events);

  return {
    id,
    presetId,
    name,
    domain,
    description,
    isActive,
    isCustom,
    entityCount: entities.size,
    eventCount: events.length,
    minDay: Number.isFinite(minDay) ? minDay : 0,
    maxDay: Number.isFinite(maxDay) ? maxDay : 0,
    channels: Array.from(channels).sort((a, b) => a.localeCompare(b)),
    actionSpace: Array.from(actionMap.entries())
      .sort((a, b) => a[0] - b[0])
      .map(([aid, label]) => ({ id: aid, label })),
    meanSpend: totalSpend / n,
    totalSpend,
    meanReward: totalReward / n,
    meanEngagement: totalEngagement / n,
    meanPropensity: totalPropensity / n,
    healthScore: health.score,
    healthTier: health.tier,
    events,
  };
}

export function buildDatasetCatalog(params: {
  presets: DatasetPreset[];
  activePresetId: string;
  customDatasetName: string | null;
  customEvents: RawEvent[] | null;
}): DatasetCatalogEntry[] {
  const { presets, activePresetId, customDatasetName, customEvents } = params;
  const entries: DatasetCatalogEntry[] = [];

  if (customDatasetName && customEvents) {
    entries.push(
      summarizeEventsForCatalog(
        'custom_csv',
        'custom_csv',
        customDatasetName,
        'Custom File Import',
        'User-imported canonical behavioral log materialized across Regression, Sequential Tensor, and Offline RL pipelines.',
        customEvents,
        true,
        true
      )
    );
  }

  for (const preset of presets) {
    const isActive = !customDatasetName && preset.id === activePresetId;
    entries.push(
      summarizeEventsForCatalog(
        preset.id,
        preset.id,
        preset.name,
        preset.domain,
        preset.description,
        preset.events,
        isActive,
        false
      )
    );
  }

  return entries;
}

export function parseDatasetSearchQuery(rawQuery: string): ParsedDatasetSearchTokens {
  const parsed: ParsedDatasetSearchTokens = {
    freeTerms: [],
    rawChips: [],
  };
  const trimmed = rawQuery.trim();
  if (!trimmed) return parsed;

  // Tokenize respecting double quotes
  const tokenRegex = /[^\s"]+|"([^"]*)"/g;
  const rawTokens: string[] = [];
  let match: RegExpExecArray | null;
  while ((match = tokenRegex.exec(trimmed)) !== null) {
    rawTokens.push(match[0]);
  }

  for (const token of rawTokens) {
    const clean = token.replace(/^"|"$/g, '');
    const lower = clean.toLowerCase();

    const colonIdx = lower.indexOf(':');
    if (colonIdx > 0) {
      const key = lower.slice(0, colonIdx);
      const val = clean.slice(colonIdx + 1).replace(/^"|"$/g, '');
      if (val) {
        if (key === 'domain') {
          parsed.domainFilter = val.toLowerCase();
          parsed.rawChips.push(`domain:${val}`);
          continue;
        }
        if (key === 'dataset' || key === 'ds') {
          parsed.datasetFilter = val.toLowerCase();
          parsed.rawChips.push(`dataset:${val}`);
          continue;
        }
        if (key === 'channel' || key === 'ch') {
          parsed.channelFilter = val.toLowerCase();
          parsed.rawChips.push(`channel:${val}`);
          continue;
        }
        if (key === 'action' || key === 'act') {
          parsed.actionFilter = val.toLowerCase();
          parsed.rawChips.push(`action:${val}`);
          continue;
        }
        if (key === 'split') {
          const sv = val.toLowerCase();
          if (sv === 'train' || sv === 'val' || sv === 'test') {
            parsed.splitFilter = sv;
            parsed.rawChips.push(`split:${sv}`);
            continue;
          }
        }
        if (key === 'entity' || key === 'id') {
          parsed.entityFilter = val.toLowerCase();
          parsed.rawChips.push(`entity:${val}`);
          continue;
        }
        if (key === 'day') {
          const range = val.match(/^(\d+)\.\.(\d+)$/);
          if (range) {
            parsed.dayMin = Number(range[1]);
            parsed.dayMax = Number(range[2]);
            parsed.rawChips.push(`day:${range[1]}..${range[2]}`);
            continue;
          }
        }
      }
    }

    const cmpMatch = lower.match(/^(spend|reward|day)(>=|<=|>|<|=)(-?\d+(?:\.\d+)?)$/);
    if (cmpMatch) {
      const field = cmpMatch[1];
      const op = cmpMatch[2];
      const num = Number(cmpMatch[3]);
      if (Number.isFinite(num)) {
        if (field === 'spend') {
          if (op === '>' || op === '>=') parsed.spendMin = op === '>' ? num + 0.0001 : num;
          else if (op === '<' || op === '<=') parsed.spendMax = op === '<' ? num - 0.0001 : num;
          else {
            parsed.spendMin = num;
            parsed.spendMax = num;
          }
          parsed.rawChips.push(`spend${op}${num}`);
          continue;
        }
        if (field === 'reward') {
          if (op === '>' || op === '>=') parsed.rewardMin = op === '>' ? num + 0.0001 : num;
          else if (op === '<' || op === '<=') parsed.rewardMax = op === '<' ? num - 0.0001 : num;
          else {
            parsed.rewardMin = num;
            parsed.rewardMax = num;
          }
          parsed.rawChips.push(`reward${op}${num}`);
          continue;
        }
        if (field === 'day') {
          if (op === '>' || op === '>=') parsed.dayMin = op === '>' ? num + 1 : num;
          else if (op === '<' || op === '<=') parsed.dayMax = op === '<' ? num - 1 : num;
          else {
            parsed.dayMin = num;
            parsed.dayMax = num;
          }
          parsed.rawChips.push(`day${op}${num}`);
          continue;
        }
      }
    }

    parsed.freeTerms.push(lower);
  }

  return parsed;
}

function scoreFreeTerms(
  terms: string[],
  primaryFields: string[],
  secondaryFields: string[]
): { matched: boolean; score: number; reasons: string[] } {
  if (terms.length === 0) {
    return { matched: true, score: 10, reasons: [] };
  }

  let score = 0;
  const reasons: string[] = [];

  for (const term of terms) {
    let bestTermScore = 0;
    let bestReason = '';

    for (const f of primaryFields) {
      const lower = f.toLowerCase();
      if (lower === term) {
        if (80 > bestTermScore) {
          bestTermScore = 80;
          bestReason = `Exact match "${term}"`;
        }
      } else if (lower.startsWith(term)) {
        if (52 > bestTermScore) {
          bestTermScore = 52;
          bestReason = `Prefix match "${term}"`;
        }
      } else if (lower.includes(term)) {
        if (34 > bestTermScore) {
          bestTermScore = 34;
          bestReason = `Title/ID match "${term}"`;
        }
      }
    }

    if (bestTermScore === 0) {
      for (const f of secondaryFields) {
        const lower = f.toLowerCase();
        if (lower.includes(term)) {
          bestTermScore = 18;
          bestReason = `Metadata match "${term}"`;
          break;
        }
      }
    }

    if (bestTermScore === 0) {
      return { matched: false, score: 0, reasons: [] };
    }
    score += bestTermScore;
    if (bestReason && !reasons.includes(bestReason)) {
      reasons.push(bestReason);
    }
  }

  return { matched: true, score, reasons };
}

function formatCompactNum(v: number): string {
  if (!Number.isFinite(v)) return '0';
  if (Math.abs(v) >= 1000) return v.toLocaleString(undefined, { maximumFractionDigits: 1 });
  return v.toFixed(2);
}

function computeCanonicalFieldStats(
  fieldKey: string,
  events: RawEvent[]
): { statsSummary: string; minVal: string; maxVal: string; meanVal: string; distinctCount: number } | null {
  if (events.length === 0) return null;
  const first = events[0] as unknown as Record<string, unknown>;
  if (!(fieldKey in first)) return null;

  const sample = first[fieldKey];
  if (typeof sample === 'number') {
    let min = Infinity;
    let max = -Infinity;
    let sum = 0;
    const distinct = new Set<number>();
    for (const ev of events) {
      const val = Number((ev as unknown as Record<string, unknown>)[fieldKey]);
      if (val < min) min = val;
      if (val > max) max = val;
      sum += val;
      if (distinct.size < 500) distinct.add(val);
    }
    const mean = sum / events.length;
    return {
      minVal: formatCompactNum(min),
      maxVal: formatCompactNum(max),
      meanVal: formatCompactNum(mean),
      distinctCount: distinct.size,
      statsSummary: `min ${formatCompactNum(min)} · mean ${formatCompactNum(mean)} · max ${formatCompactNum(max)}`,
    };
  }

  const distinctStr = new Set<string>();
  for (const ev of events) {
    distinctStr.add(String((ev as unknown as Record<string, unknown>)[fieldKey] ?? ''));
  }
  return {
    minVal: '—',
    maxVal: '—',
    meanVal: '—',
    distinctCount: distinctStr.size,
    statsSummary: `${distinctStr.size.toLocaleString()} distinct values`,
  };
}

export function executeDatasetSearch(params: {
  query: string;
  filters: DatasetSearchFilters;
  catalog: DatasetCatalogEntry[];
  globalConfig: GlobalCurationConfig;
  obsCutoffDay: number;
  limit?: number;
}): DatasetSearchReport {
  const { query, filters, catalog, globalConfig, obsCutoffDay, limit = 80 } = params;
  const parsed = parseDatasetSearchQuery(query);

  const channelSet = new Set<string>();
  for (const ds of catalog) {
    for (const ch of ds.channels) channelSet.add(ch);
  }
  const availableChannels = Array.from(channelSet).sort((a, b) => a.localeCompare(b));

  const effectiveChannel =
    filters.channel !== 'all' ? filters.channel.toLowerCase() : parsed.channelFilter;
  const effectiveSplit: SplitName | undefined =
    filters.split !== 'all' ? filters.split : parsed.splitFilter;
  const effectiveMinSpend =
    filters.minSpend !== null && Number.isFinite(filters.minSpend)
      ? Math.max(filters.minSpend, parsed.spendMin ?? -Infinity)
      : parsed.spendMin;

  const matchingDatasets = catalog.filter((ds) => {
    if (filters.datasetId !== 'all' && ds.id !== filters.datasetId) return false;
    if (
      parsed.datasetFilter &&
      !ds.id.toLowerCase().includes(parsed.datasetFilter) &&
      !ds.name.toLowerCase().includes(parsed.datasetFilter)
    ) {
      return false;
    }
    if (parsed.domainFilter && !ds.domain.toLowerCase().includes(parsed.domainFilter)) {
      return false;
    }
    if (
      effectiveChannel &&
      !ds.channels.some((c) => c.toLowerCase().includes(effectiveChannel))
    ) {
      return false;
    }
    if (
      parsed.actionFilter &&
      !ds.actionSpace.some((a) => a.label.toLowerCase().includes(parsed.actionFilter!))
    ) {
      return false;
    }
    return true;
  });

  const allHits: DatasetSearchHit[] = [];

  // 1. Dataset Catalog hits
  const hasEventOnlyConstraints =
    effectiveMinSpend !== undefined ||
    parsed.spendMax !== undefined ||
    parsed.rewardMin !== undefined ||
    parsed.rewardMax !== undefined ||
    parsed.dayMin !== undefined ||
    parsed.dayMax !== undefined ||
    Boolean(parsed.entityFilter) ||
    Boolean(effectiveSplit);

  if (!hasEventOnlyConstraints) {
    for (const ds of matchingDatasets) {
      const termMatch = scoreFreeTerms(
        parsed.freeTerms,
        [ds.name, ds.id, ds.domain],
        [
          ds.description,
          ...ds.channels,
          ...ds.actionSpace.map((a) => a.label),
          ds.isActive ? 'active' : '',
        ]
      );
      if (!termMatch.matched) continue;

      const reasons = [...termMatch.reasons];
      if (ds.isActive) reasons.push('Active Workspace');
      allHits.push({
        id: `ds-${ds.id}`,
        kind: 'dataset',
        datasetId: ds.id,
        datasetName: ds.name,
        datasetDomain: ds.domain,
        isActiveDataset: ds.isActive,
        title: ds.name,
        subtitle: `${ds.domain} · ${ds.entityCount} entities · ${ds.eventCount.toLocaleString()} events · Days ${ds.minDay}–${ds.maxDay}`,
        primaryMetricLabel: 'Data Health',
        primaryMetricValue: `${ds.healthScore}/100`,
        score: termMatch.score + (ds.isActive ? 14 : 6),
        matchReasons: reasons.length > 0 ? reasons : ['Indexed Catalog'],
        catalogEntry: ds,
      });
    }
  }

  // 2. Schema / Materialized Field hits (scoped to active dataset or selected dataset)
  const schemaTargetDs =
    matchingDatasets.find((d) =>
      filters.datasetId !== 'all' ? d.id === filters.datasetId : d.isActive
    ) ?? matchingDatasets[0];

  if (schemaTargetDs && !hasEventOnlyConstraints && !effectiveChannel && !parsed.actionFilter) {
    for (const field of CANONICAL_AND_MATERIALIZED_FIELDS) {
      const termMatch = scoreFreeTerms(
        parsed.freeTerms,
        [field.columnName, field.fieldKey],
        [field.description, field.tableName, field.paradigm, field.dataType]
      );
      if (!termMatch.matched) continue;

      const computed = computeCanonicalFieldStats(field.fieldKey, schemaTargetDs.events);
      allHits.push({
        id: `schema-${schemaTargetDs.id}-${field.tableName}-${field.columnName}`,
        kind: 'schema',
        datasetId: schemaTargetDs.id,
        datasetName: schemaTargetDs.name,
        datasetDomain: schemaTargetDs.domain,
        isActiveDataset: schemaTargetDs.isActive,
        title: field.columnName,
        subtitle: `${field.tableName} (${field.dataType}) · ${field.description}`,
        primaryMetricLabel: field.paradigm,
        primaryMetricValue: computed?.statsSummary ?? field.dataType,
        score: termMatch.score + (field.paradigm === 'Canonical' ? 4 : 2),
        matchReasons:
          termMatch.reasons.length > 0 ? termMatch.reasons : [`${field.paradigm} Schema`],
        fieldSchema: {
          ...field,
          ...(computed ?? {}),
        },
      });
    }
  }

  // 3. Entity-level aggregation hits across matching datasets
  for (const ds of matchingDatasets) {
    const entityMap = new Map<
      string,
      {
        events: RawEvent[];
        totalSpend: number;
        totalReward: number;
        totalEng: number;
        firstDay: number;
        lastDay: number;
        channels: Set<string>;
        actions: Set<string>;
      }
    >();

    for (const ev of ds.events) {
      let bucket = entityMap.get(ev.entityId);
      if (!bucket) {
        bucket = {
          events: [],
          totalSpend: 0,
          totalReward: 0,
          totalEng: 0,
          firstDay: ev.timestampDay,
          lastDay: ev.timestampDay,
          channels: new Set<string>(),
          actions: new Set<string>(),
        };
        entityMap.set(ev.entityId, bucket);
      }
      bucket.events.push(ev);
      bucket.totalSpend += ev.spendAmount;
      bucket.totalReward += ev.reward;
      bucket.totalEng += ev.engagementScore;
      if (ev.timestampDay < bucket.firstDay) bucket.firstDay = ev.timestampDay;
      if (ev.timestampDay > bucket.lastDay) bucket.lastDay = ev.timestampDay;
      bucket.channels.add(ev.channel);
      bucket.actions.add(ev.actionLabel);
    }

    let entityHitsInDs = 0;
    for (const [entityId, agg] of entityMap.entries()) {
      const split = assignEntitySplit(entityId, globalConfig);
      if (effectiveSplit && split !== effectiveSplit) continue;
      if (parsed.entityFilter && !entityId.toLowerCase().includes(parsed.entityFilter)) continue;

      const chList = Array.from(agg.channels);
      const actList = Array.from(agg.actions);
      if (
        effectiveChannel &&
        !chList.some((c) => c.toLowerCase().includes(effectiveChannel))
      ) {
        continue;
      }
      if (
        parsed.actionFilter &&
        !actList.some((a) => a.toLowerCase().includes(parsed.actionFilter!))
      ) {
        continue;
      }
      if (effectiveMinSpend !== undefined && agg.totalSpend < effectiveMinSpend) continue;
      if (parsed.spendMax !== undefined && agg.totalSpend > parsed.spendMax) continue;
      const meanReward = agg.totalReward / Math.max(1, agg.events.length);
      if (parsed.rewardMin !== undefined && meanReward < parsed.rewardMin) continue;
      if (parsed.rewardMax !== undefined && meanReward > parsed.rewardMax) continue;
      if (parsed.dayMin !== undefined && agg.lastDay < parsed.dayMin) continue;
      if (parsed.dayMax !== undefined && agg.firstDay > parsed.dayMax) continue;

      const termMatch = scoreFreeTerms(
        parsed.freeTerms,
        [entityId],
        [ds.name, ds.domain, split, ...chList, ...actList]
      );
      if (!termMatch.matched) continue;

      const reasons = [...termMatch.reasons];
      if (parsed.rawChips.length > 0) reasons.push(...parsed.rawChips.slice(0, 2));

      const sortedRecent = [...agg.events].sort((a, b) => b.timestampDay - a.timestampDay);

      allHits.push({
        id: `entity-${ds.id}-${entityId}`,
        kind: 'entity',
        datasetId: ds.id,
        datasetName: ds.name,
        datasetDomain: ds.domain,
        isActiveDataset: ds.isActive,
        title: entityId,
        subtitle: `${ds.name} · ${split.toUpperCase()} · ${agg.events.length} events · Days ${agg.firstDay}–${agg.lastDay}`,
        primaryMetricLabel: 'Total Spend',
        primaryMetricValue: `$${agg.totalSpend.toLocaleString(undefined, { maximumFractionDigits: 0 })}`,
        score: termMatch.score + (ds.isActive ? 5 : 0),
        matchReasons: reasons.length > 0 ? reasons : ['Entity Cohort'],
        entitySummary: {
          entityId,
          split,
          eventCount: agg.events.length,
          firstDay: agg.firstDay,
          lastDay: agg.lastDay,
          totalSpend: agg.totalSpend,
          meanReward,
          meanEngagement: agg.totalEng / Math.max(1, agg.events.length),
          channels: chList,
          actions: actList,
          recentEvents: sortedRecent.slice(0, 8),
        },
      });

      entityHitsInDs += 1;
      // Cap per-dataset entity scan when browsing without narrow query
      if (parsed.freeTerms.length === 0 && !parsed.entityFilter && entityHitsInDs >= 20) {
        break;
      }
    }
  }

  // 4. Individual Event hits across matching datasets
  for (const ds of matchingDatasets) {
    let eventHitsInDs = 0;
    for (const ev of ds.events) {
      const split = assignEntitySplit(ev.entityId, globalConfig);
      if (effectiveSplit && split !== effectiveSplit) continue;
      if (parsed.entityFilter && !ev.entityId.toLowerCase().includes(parsed.entityFilter)) continue;
      if (effectiveChannel && !ev.channel.toLowerCase().includes(effectiveChannel)) continue;
      if (parsed.actionFilter && !ev.actionLabel.toLowerCase().includes(parsed.actionFilter)) {
        continue;
      }
      if (effectiveMinSpend !== undefined && ev.spendAmount < effectiveMinSpend) continue;
      if (parsed.spendMax !== undefined && ev.spendAmount > parsed.spendMax) continue;
      if (parsed.rewardMin !== undefined && ev.reward < parsed.rewardMin) continue;
      if (parsed.rewardMax !== undefined && ev.reward > parsed.rewardMax) continue;
      if (parsed.dayMin !== undefined && ev.timestampDay < parsed.dayMin) continue;
      if (parsed.dayMax !== undefined && ev.timestampDay > parsed.dayMax) continue;

      const termMatch = scoreFreeTerms(
        parsed.freeTerms,
        [ev.eventId, ev.entityId, ev.actionLabel],
        [ev.channel, ds.name, ds.domain, split, `day ${ev.timestampDay}`]
      );
      if (!termMatch.matched) continue;

      const windowPhase: 'obs' | 'horizon' =
        ev.timestampDay <= obsCutoffDay ? 'obs' : 'horizon';

      allHits.push({
        id: `event-${ds.id}-${ev.eventId}`,
        kind: 'event',
        datasetId: ds.id,
        datasetName: ds.name,
        datasetDomain: ds.domain,
        isActiveDataset: ds.isActive,
        title: `${ev.eventId} · ${ev.entityId}`,
        subtitle: `${ds.name} · Day ${ev.timestampDay} · ${ev.actionLabel} via ${ev.channel}`,
        primaryMetricLabel: 'Spend / Reward',
        primaryMetricValue: `$${ev.spendAmount.toFixed(2)} / ${ev.reward.toFixed(2)}`,
        score: termMatch.score + (ds.isActive ? 3 : 0),
        matchReasons:
          termMatch.reasons.length > 0
            ? termMatch.reasons
            : parsed.rawChips.length > 0
              ? parsed.rawChips
              : ['Event Stream'],
        eventRecord: {
          ...ev,
          split,
          windowPhase,
        },
      });

      eventHitsInDs += 1;
      if (parsed.freeTerms.length === 0 && parsed.rawChips.length === 0 && eventHitsInDs >= 20) {
        break;
      }
    }
  }

  // Sort by score descending, active dataset first, then title
  allHits.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score;
    if (a.isActiveDataset !== b.isActiveDataset) return a.isActiveDataset ? -1 : 1;
    return a.title.localeCompare(b.title);
  });

  const countsByKind: Record<DatasetSearchHitKind, number> = {
    dataset: 0,
    schema: 0,
    entity: 0,
    event: 0,
  };
  for (const h of allHits) {
    countsByKind[h.kind] += 1;
  }

  const filteredByKind =
    filters.kind === 'all' ? allHits : allHits.filter((h) => h.kind === filters.kind);

  return {
    query,
    parsed,
    totalHits: filteredByKind.length,
    countsByKind,
    hits: filteredByKind.slice(0, limit),
    availableChannels,
  };
}
